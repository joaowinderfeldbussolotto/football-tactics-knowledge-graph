"""``summary.md`` from ``results.jsonl``. Pure function of the file: no LLM, no Neo4j."""

import json
from collections import defaultdict
from pathlib import Path
from statistics import mean

from football_graphrag.benchmark.arms import ARMS
from football_graphrag.benchmark.questions import QUESTION_TYPES
from football_graphrag.benchmark.scoring import canonical_name


def load_rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def _pct(values: list[bool]) -> str:
    return f"{100 * mean(values):.0f}%" if values else "–"


def _answer_key(row: dict) -> tuple:
    """What counts as "the same answer" across repeats."""
    a = row["answer"]
    if a is None:
        return ("no_valid_answer",)
    return (tuple(canonical_name(p) for p in a["players"]), a["value"], a["no_data"])


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def summarize(rows: list[dict]) -> str:
    arms = [a for a in ARMS if any(r["arm"] == a for r in rows)]
    types = [t for t in QUESTION_TYPES if any(r["type"] == t for r in rows)]
    by_arm = defaultdict(list)
    for r in rows:
        by_arm[r["arm"]].append(r)

    n_questions = len({r["question_id"] for r in rows})
    repeats = sorted({r["repeat"] for r in rows})
    models = sorted({r["model"] for r in rows})
    out = [
        "# Benchmark results",
        "",
        f"{len(rows)} runs: {n_questions} questions, arms {', '.join(arms)}, "
        f"repeats {', '.join(map(str, repeats))}. Model: {', '.join(models)}.",
        "",
        "Generated by `scripts/summarize.py` from `results.jsonl`. Every number is a share of runs "
        "(each repeat counts), scored by code against `ground_truth.json`.",
    ]

    # 1. accuracy by type x arm
    body = []
    for t in types:
        body.append([t] + [_pct([r["correct"] for r in by_arm[a] if r["type"] == t]) for a in arms])
    body.append(["**all**"] + [f"**{_pct([r['correct'] for r in by_arm[a]])}**" for a in arms])
    body.append(["**all but unanswerable**"] + [
        f"**{_pct([r['correct'] for r in by_arm[a] if r['type'] != 'unanswerable'])}**" for a in arms])
    out += [
        "", "## 1. Accuracy by question type and arm", "",
        "An arm that always answers \"no data\" gets every unanswerable question right; the last row "
        "leaves them out.",
        "", _table(["type"] + arms, body),
    ]

    # 2-3. kinds of error
    body = []
    for a in arms:
        rs = by_arm[a]
        halluc = [not r["correct"] and not r["abstention"] and not r["format_error"] for r in rs]
        body.append([a, _pct(halluc), _pct([r["abstention"] for r in rs]), _pct([r["format_error"] for r in rs])])
    out += [
        "", "## 2. Errors by arm", "",
        "Hallucination: a wrong answer given as an answer (not an abstention, not a format error). "
        "On unanswerable questions, any answer other than `no_data` is a hallucination. "
        "Abstention: `no_data` on a question that has an answer. "
        "Format error: no valid `Answer` after the output retries (or the tool/request limit was hit).",
        "",
        _table(["arm", "hallucination", "abstention", "format error"], body),
    ]

    # 4. consistency across repeats
    body = []
    for a in arms:
        per_q = defaultdict(list)
        for r in by_arm[a]:
            per_q[r["question_id"]].append(_answer_key(r))
        multi = [len(set(keys)) == 1 for keys in per_q.values() if len(keys) > 1]
        body.append([a, _pct(multi), str(len(multi))])
    out += [
        "", "## 3. Consistency across repeats", "",
        "Share of questions whose repeats gave the same answer (same players, value and no_data).",
        "", _table(["arm", "same answer", "questions with >1 repeat"], body),
    ]

    # 5. cost
    body = []
    for a in arms:
        rs = by_arm[a]
        body.append([
            a,
            f"{mean(r['input_tokens'] for r in rs):,.0f}",
            f"{mean(r['output_tokens'] for r in rs):,.0f}",
            f"{mean(r['n_tool_calls'] for r in rs):.1f}",
            f"{mean(r['latency_s'] for r in rs):.1f}",
        ])
    out += [
        "", "## 4. Cost per question", "",
        _table(["arm", "input tokens", "output tokens", "tool calls", "latency (s)"], body),
    ]

    # per-question detail
    qids = sorted({r["question_id"] for r in rows}, key=lambda q: ("fansu".index(q[0]), q))
    body = []
    for q in qids:
        cells = []
        for a in arms:
            rs = [r for r in by_arm[a] if r["question_id"] == q]
            cells.append(f"{sum(r['correct'] for r in rs)}/{len(rs)}" if rs else "–")
        body.append([q] + cells)
    out += ["", "## 5. Correct runs per question", "", _table(["question"] + arms, body), ""]
    return "\n".join(out)


def summary_path_for(results: Path) -> Path:
    """results.jsonl -> summary.md; <x>_results.jsonl -> <x>_summary.md; anything
    else -> <stem>_summary.md."""
    if results.name == "results.jsonl":
        return results.with_name("summary.md")
    if results.stem.endswith("_results"):
        return results.with_name(f"{results.stem.removesuffix('_results')}_summary.md")
    return results.with_name(f"{results.stem}_summary.md")


def write_summary(results_path: Path) -> Path:
    path = summary_path_for(results_path)
    path.write_text(summarize(load_rows(results_path)))
    return path
